/* The published catalogue holds together: play/levels.json, the image manifest, the files on
   disk, the service worker's precache list and the numbers the pages quote. Each check here is a
   way the site has drifted, or could drift, without any one file looking wrong on its own. */
import { existsSync, readdirSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { parseLibrary, totalTargets } from "../../play/core/index.js";
import { readRepoJSON, readRepoText, repoPath } from "../fixtures/repo.js";

const raw = readRepoJSON("play/levels.json");
const library = parseLibrary(raw);
const manifest = readRepoJSON("assets/paintings.json");
const totalThings = library.levels.reduce((n, l) => n + totalTargets(l), 0);

describe("play/levels.json", () => {
  it("is the generated file, and parses as the game reads it", () => {
    expect(raw.note).toMatch(/Generated by tools\/make-play-data\.mjs/);
    expect(library.levels.length).toBeGreaterThan(0);
  });

  it("publishes none of the family's own pictures", () => {
    const personal = new Set(library.collections.filter((c) => c.personal).map((c) => c.id));
    expect(personal.size).toBeGreaterThan(0); // the row itself is published, as an invitation
    expect(library.levels.filter((l) => personal.has(l.collection))).toEqual([]);
  });

  it("has unique level ids and unique item ids within each level", () => {
    const ids = library.levels.map((l) => l.id);
    expect(new Set(ids).size).toBe(ids.length);
    for (const l of library.levels) {
      const groups = l.items.map((g) => g.id);
      expect(new Set(groups).size, l.id).toBe(groups.length);
    }
  });

  it("does not use '#' in an item id, so target keys stay unambiguous", () => {
    for (const l of library.levels) for (const g of l.items) expect(g.id, `${l.id}/${g.id}`).not.toContain("#");
  });

  it("puts every level in a known collection", () => {
    const known = new Set(library.collections.map((c) => c.id));
    for (const l of library.levels) expect(known.has(l.collection), `${l.id} in "${l.collection}"`).toBe(true);
  });

  it("has an English title, artist and positive pixel size for every painting", () => {
    for (const l of library.levels) {
      expect(l.titles.en, l.id).toBeTruthy();
      expect(l.artist, l.id).toBeTruthy();
      expect(Number.isInteger(l.aspect.w) && l.aspect.w > 0, l.id).toBe(true);
      expect(Number.isInteger(l.aspect.h) && l.aspect.h > 0, l.id).toBe(true);
    }
  });

  it("gives every item an English name and at least one target", () => {
    for (const l of library.levels) {
      expect(l.items.length, l.id).toBeGreaterThan(0);
      for (const g of l.items) {
        expect(g.names.en, `${l.id}/${g.id}`).toBeTruthy();
        expect(g.targets.length, `${l.id}/${g.id}`).toBeGreaterThan(0);
      }
    }
  });

  it("keeps every target on the painting with a sensible tap radius", () => {
    for (const l of library.levels) {
      for (const g of l.items) {
        g.targets.forEach((t, i) => {
          const where = `${l.id}/${g.id}#${i}`;
          expect(t.x, where).toBeGreaterThanOrEqual(0);
          expect(t.x, where).toBeLessThanOrEqual(1);
          expect(t.y, where).toBeGreaterThanOrEqual(0);
          expect(t.y, where).toBeLessThanOrEqual(1);
          expect(t.r, where).toBeGreaterThan(0);
          expect(t.r, where).toBeLessThanOrEqual(0.25);
        });
      }
    }
  });

  it("keeps crop rects (thumbs, stickers) inside the painting", () => {
    const inside = (r, where) => {
      expect(r.w, where).toBeGreaterThan(0);
      expect(r.h, where).toBeGreaterThan(0);
      expect(r.x, where).toBeGreaterThanOrEqual(-1e-9);
      expect(r.y, where).toBeGreaterThanOrEqual(-1e-9);
      expect(r.x + r.w, where).toBeLessThanOrEqual(1 + 1e-9);
      expect(r.y + r.h, where).toBeLessThanOrEqual(1 + 1e-9);
    };
    for (const l of library.levels) {
      if (l.sticker) inside(l.sticker, `${l.id} sticker`);
      for (const g of l.items) if (g.thumb) inside(g.thumb, `${l.id}/${g.id} thumb`);
    }
  });
});

describe("assets/paintings.json against play/levels.json", () => {
  it("has exactly the published levels", () => {
    expect(Object.keys(manifest.levels).sort()).toEqual(library.levels.map((l) => l.id).sort());
  });

  it("agrees on each painting's pixel size (a wrong aspect moves every target)", () => {
    for (const l of library.levels) expect(manifest.levels[l.id].aspect, l.id).toEqual(l.aspect);
  });

  it("has every tier the game asks for, in the formats it asks for", () => {
    for (const l of library.levels) {
      const t = manifest.levels[l.id].tiers;
      for (const tier of ["card", "fit"]) {
        expect(t[tier]?.avif?.path, `${l.id} ${tier}.avif`).toBeTruthy();
        expect(t[tier]?.webp?.path, `${l.id} ${tier}.webp`).toBeTruthy();
      }
      // `fit` is where a browser without AVIF stays, so it must carry WebP (checked above).
      for (const tier of ["play", "zoom"]) expect(t[tier]?.avif?.path, `${l.id} ${tier}.avif`).toBeTruthy();
    }
  });

  it("has a HUD thumb for every item and a sticker for every painting", () => {
    for (const l of library.levels) {
      const m = manifest.levels[l.id];
      for (const g of l.items) expect(m.thumbs[g.id]?.avif?.path, `${l.id}/${g.id}`).toBeTruthy();
      expect(m.sticker?.avif?.path, l.id).toBeTruthy();
      expect(m.sticker?.webp?.path, l.id).toBeTruthy();
    }
  });

  it("names only files that exist", () => {
    const missing = [];
    const check = (e) => {
      for (const f of ["avif", "webp"]) {
        if (e?.[f]?.path && !existsSync(repoPath("assets", manifest.base, e[f].path))) missing.push(e[f].path);
      }
    };
    for (const m of Object.values(manifest.levels)) {
      Object.values(m.tiers).forEach(check);
      Object.values(m.thumbs).forEach(check);
      check(m.sticker);
    }
    expect(missing).toEqual([]);
  });
});

describe("service worker", () => {
  const sw = readRepoText("sw.js");
  const shell = JSON.parse(sw.match(/var SHELL = (\[[\s\S]*?\]);/)[1].replace(/'/g, '"'));

  it("precaches every file the game shell loads, and nothing that is not there", () => {
    const onDisk = (dir) => readdirSync(repoPath(dir), { withFileTypes: true }).flatMap((e) =>
      e.isDirectory() ? onDisk(`${dir}/${e.name}`) : [`${dir}/${e.name}`]);
    const files = onDisk("play").filter((f) => !f.endsWith("index.html")).sort();
    expect(shell.filter((f) => f !== "play/").sort()).toEqual(files);
    expect(shell).toContain("play/");
  });

  it("precaches the manifest's own path", () => {
    expect(sw).toMatch(/var MANIFEST = 'assets\/paintings\.json'/);
  });
});

describe("pages", () => {
  const home = readRepoText("index.html");
  const play = readRepoText("play/index.html");

  it("quote the number of paintings the demo actually has", () => {
    const n = library.levels.length;
    expect(home).toContain(`${n} paintings, ${totalThings} things to find`);
    expect(home).toContain(`Play all ${n} paintings`);
    expect(play).toMatch(new RegExp(`content="[^"]*\\b${n} famous paintings`));
  });

  it("have every element the game script looks up by id", () => {
    const ids = new Set([...play.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
    for (const file of ["play/app.js", "play/game.js"]) {
      for (const [, id] of readRepoText(file).matchAll(/\$\("([^"]+)"\)/g)) {
        expect(ids.has(id), `${file} looks up #${id}`).toBe(true);
      }
    }
  });

  it("install to the game", () => {
    const webmanifest = readRepoJSON("manifest.webmanifest");
    expect(webmanifest.start_url).toBe("/play/");
    for (const icon of webmanifest.icons) expect(existsSync(repoPath(icon.src)), icon.src).toBe(true);
  });
});
