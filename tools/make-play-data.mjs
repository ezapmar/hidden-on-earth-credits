#!/usr/bin/env node
/* Publishes the game's level data for the web build.
 *
 * The image manifest (assets/paintings.json) carries pixel sizes and file paths but no targets,
 * because the Swift app reads those from its own bundle. The web game needs them, so this emits
 * play/levels.json from the game's levels.json.
 *
 * Levels in a collection marked "personal": true are the family's own pictures and are NEVER
 * published, matching tools/build-images.mjs, which refuses them by default. This repository is
 * public.
 *
 *   node tools/make-play-data.mjs [--levels <path>] [--out play/levels.json]
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DEFAULT_LEVELS = path.resolve(REPO, "../seek-and-find/SeekAndFind/Resources/levels.json");

const args = process.argv.slice(2);
let levelsPath = DEFAULT_LEVELS;
let outPath = path.resolve(REPO, "play/levels.json");
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--levels") levelsPath = path.resolve(args[++i]);
  else if (args[i] === "--out") outPath = path.resolve(args[++i]);
  else {
    console.error(`unknown argument ${args[i]}`);
    process.exit(2);
  }
}

const file = JSON.parse(await fs.readFile(levelsPath, "utf8"));
const collections = file.collections ?? [];
const personal = new Set(collections.filter((c) => c.personal).map((c) => c.id));

const kept = [];
const refused = [];
for (const level of file.levels) {
  if (personal.has(level.collection)) {
    refused.push(level.id);
    continue;
  }
  // Only what the game needs to play. No source paths, no encoder settings.
  kept.push({
    id: level.id,
    titles: level.titles,
    artist: level.artist,
    imageName: level.imageName,
    aspect: level.aspect,
    ...(level.collection === undefined ? {} : { collection: level.collection }),
    ...(level.sticker === undefined ? {} : { sticker: level.sticker }),
    items: level.items.map((g) => ({
      id: g.id,
      names: g.names,
      targets: g.targets,
      ...(g.thumb === undefined ? {} : { thumb: g.thumb }),
    })),
  });
}

const out = {
  note: "Generated by tools/make-play-data.mjs from the game's levels.json. Do not edit by hand.",
  collections: collections.filter((c) => !c.personal),
  levels: kept,
};
await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, JSON.stringify(out, null, 1) + "\n");

const targets = kept.reduce((n, l) => n + l.items.reduce((m, g) => m + g.targets.length, 0), 0);
console.log(`wrote ${path.relative(REPO, outPath)}`);
console.log(`  published ${kept.length} levels, ${targets} targets`);
console.log(`  refused ${refused.length} personal: ${refused.join(", ") || "none"}`);
