#!/usr/bin/env node
/* Publishes the game's level data for the web build.
 *
 * The image manifest (assets/paintings.json) carries pixel sizes and file paths but no targets,
 * because the Swift app reads those from its own bundle. The web game needs them, so this emits
 * play/levels.json from the game's levels.json.
 *
 * Levels in a collection marked "personal": true are the family's own pictures and are NEVER
 * published, matching tools/build-images.mjs, which refuses them by default. This repository is
 * public.
 *
 *   node tools/make-play-data.mjs [--levels <path>] [--out play/levels.json] [--check]
 *
 * --check writes nothing and exits non-zero if the committed copy is out of date, so CI can
 * catch a painting that was edited in the game and never republished here.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DEFAULT_LEVELS = path.resolve(REPO, "../seek-and-find/SeekAndFind/Resources/levels.json");

const args = process.argv.slice(2);
let levelsPath = DEFAULT_LEVELS;
let outPath = path.resolve(REPO, "play/levels.json");
let check = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--levels") levelsPath = path.resolve(args[++i]);
  else if (args[i] === "--out") outPath = path.resolve(args[++i]);
  else if (args[i] === "--check") check = true;
  else {
    console.error(`unknown argument ${args[i]}`);
    process.exit(2);
  }
}

const file = JSON.parse(await fs.readFile(levelsPath, "utf8"));
const collections = file.collections ?? [];
const personal = new Set(collections.filter((c) => c.personal).map((c) => c.id));

// `/play` is a public DEMO, not the full game: the iPad app carries the whole catalogue, the web
// build carries a fixed small set. Growing the game must never silently bloat the demo, so the
// demo's paintings are listed here explicitly. Edit this list (not the game) to change the demo.
const DEMO = new Set([
  "seurat_grande_jatte",
  "rousseau_tropical_forest",
  "hicks_peaceable_kingdom",
  "rousseau_surprised",
  "brueghel_noahs_ark",
  "hondecoeter_menagerie",
  "savery_landscape_with_birds",
  "bruegel_hunters_in_the_snow",
  "avercamp_winter_landscape",
  "vangogh_starry_night",
  "bruegel_childrens_games",
  "hokusai_great_wave",
  "cezanne_apples_and_oranges",
  "peale_blackberries",
]);

const kept = [];
const refused = [];
const notInDemo = [];
const seenDemo = new Set();
for (const level of file.levels) {
  if (personal.has(level.collection)) {
    refused.push(level.id);
    continue;
  }
  if (!DEMO.has(level.id)) {
    notInDemo.push(level.id);
    continue;
  }
  seenDemo.add(level.id);
  // Only what the game needs to play. No source paths, no encoder settings.
  kept.push({
    id: level.id,
    titles: level.titles,
    artist: level.artist,
    imageName: level.imageName,
    aspect: level.aspect,
    ...(level.collection === undefined ? {} : { collection: level.collection }),
    ...(level.sticker === undefined ? {} : { sticker: level.sticker }),
    items: level.items.map((g) => ({
      id: g.id,
      names: g.names,
      targets: g.targets,
      ...(g.thumb === undefined ? {} : { thumb: g.thumb }),
    })),
  });
}

const missing = [...DEMO].filter((id) => !seenDemo.has(id));
if (missing.length) {
  console.error(`demo list names ${missing.length} painting(s) not in the game: ${missing.join(", ")}`);
  process.exit(2);
}

const out = {
  note: "Generated by tools/make-play-data.mjs from the game's levels.json. Do not edit by hand.",
  // Every collection, including the personal one. A row's id, name and symbol are not personal
  // data; its pictures are, and those are refused above. Publishing the row lets the picker
  // show the same "add your own picture" invitation the Swift home screen shows, which is an
  // invitation rather than a control until the web editor exists.
  collections,
  levels: kept,
};
const text = JSON.stringify(out, null, 1) + "\n";
const current = await fs.readFile(outPath, "utf8").catch(() => null);

if (check) {
  if (current === text) {
    console.log(`${path.relative(REPO, outPath)} is up to date`);
    process.exit(0);
  }
  console.error(`${path.relative(REPO, outPath)} is out of date — run: npm run play:data`);
  console.error(current === null ? "  it does not exist" : "  the game's levels.json has changed since it was generated");
  process.exit(1);
}

await fs.mkdir(path.dirname(outPath), { recursive: true });
await fs.writeFile(outPath, text);

const targets = kept.reduce((n, l) => n + l.items.reduce((m, g) => m + g.targets.length, 0), 0);
console.log(`wrote ${path.relative(REPO, outPath)}`);
console.log(`  published ${kept.length} levels, ${targets} targets`);
console.log(`  refused ${refused.length} personal: ${refused.join(", ") || "none"}`);
console.log(`  held back ${notInDemo.length} not in the demo list`);
